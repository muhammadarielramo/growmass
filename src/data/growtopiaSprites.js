export function getVerifiedItemImage(itemName) {
  if (!itemName) return null;
  const clean = itemName
    .toLowerCase()
    .trim()
    .replace(/ (seed|seeds|block|blocks|tree|trees)$/i, "")
    .trim();

  // 1. Direct match
  if (VERIFIED_ITEM_SPRITES[clean]) return VERIFIED_ITEM_SPRITES[clean];
  if (VERIFIED_ITEM_SPRITES[itemName.toLowerCase().trim()]) return VERIFIED_ITEM_SPRITES[itemName.toLowerCase().trim()];

  // 2. Partial match
  for (const [key, url] of Object.entries(VERIFIED_ITEM_SPRITES)) {
    if (clean.includes(key) || key.includes(clean)) {
      return url;
    }
  }

  return null;
}
